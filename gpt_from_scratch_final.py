class EarlyStopping:
    def __init__(self, patience=7, min_delta=1e-3):
        self.patience = patience
        self.min_delta = min_delta
        self.best = float('inf')
        self.bad = 0

    def step(self, val_loss):
        if val_loss < self.best - self.min_delta:
            self.best = val_loss
            self.bad = 0
            return False, True
        self.bad += 1
        return (self.bad >= self.patience), False

